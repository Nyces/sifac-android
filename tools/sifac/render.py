"""Software textured preview for Blade meshes (characters and stages).

Two projections are supported:

* ``camera=None`` — a front orthographic view fitted to the geometry, used for
  character previews and the regression tests.
* :class:`Camera` — a perspective camera, needed for stages and the live scene.

Body and hair meshes store world-space vertices and skin normally. Eye meshes
(stride 44) are stored in their node's local space and face meshes (stride 60)
carry an origin at the character root, so both must be anchored to their node
before rendering; ``sifac.cli._attach_rigid_meshes`` does that.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

from .texture import BtxTexture, encode_png

BACKGROUND = (16, 18, 24, 255)
ADDITIVE_GAIN = 0.35
ADDITIVE_NAMES = ("lightbar", "floor_frame", "yuka_led", "mon_dotmask")


@dataclass(frozen=True)
class Camera:
    position: tuple[float, float, float]
    target: tuple[float, float, float]
    up: tuple[float, float, float] = (0.0, 0.0, 1.0)
    fov_degrees: float = 45.0

    def matrices(
        self, aspect: float, near: float = 0.05, far: float = 200.0
    ) -> list[list[float]]:
        return _mat_mul(
            _perspective(self.fov_degrees, aspect, near, far),
            _look_at(self.position, self.target, self.up),
        )


def _normalize(v: tuple[float, float, float]) -> tuple[float, float, float]:
    length = math.sqrt(sum(c * c for c in v)) or 1.0
    return (v[0] / length, v[1] / length, v[2] / length)


def _cross(a, b) -> tuple[float, float, float]:
    return (
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    )


def _dot(a, b) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def _mat_mul(a: list[list[float]], b: list[list[float]]) -> list[list[float]]:
    return [
        [sum(a[i][k] * b[k][j] for k in range(4)) for j in range(4)]
        for i in range(4)
    ]


def _look_at(eye, target, up) -> list[list[float]]:
    forward = _normalize((target[0] - eye[0], target[1] - eye[1], target[2] - eye[2]))
    side = _normalize(_cross(forward, up))
    true_up = _cross(side, forward)
    return [
        [side[0], side[1], side[2], -_dot(side, eye)],
        [true_up[0], true_up[1], true_up[2], -_dot(true_up, eye)],
        [-forward[0], -forward[1], -forward[2], _dot(forward, eye)],
        [0.0, 0.0, 0.0, 1.0],
    ]


def _perspective(fov_degrees: float, aspect: float, near: float, far: float) -> list[list[float]]:
    f = 1.0 / math.tan(math.radians(fov_degrees) * 0.5)
    return [
        [f / aspect, 0.0, 0.0, 0.0],
        [0.0, f, 0.0, 0.0],
        [0.0, 0.0, (far + near) / (near - far), 2.0 * far * near / (near - far)],
        [0.0, 0.0, -1.0, 0.0],
    ]


def _screen_bounds(meshes: list) -> tuple[float, float, float, float]:
    points = [p for mesh in meshes for p in mesh.positions]
    if not points:
        raise ValueError("no vertices to render")
    return (
        min(p[0] for p in points),
        max(p[0] for p in points),
        min(p[2] for p in points),
        max(p[2] for p in points),
    )


class _Surface:
    """Lazily decoded btx mip chain for one material.

    Some btx files carry a single level; the remaining levels are generated by
    box filtering so that distant, heavily tiled surfaces stop shimmering.
    """

    def __init__(self, texture: BtxTexture) -> None:
        self.texture = texture
        self.count = max(1, texture.levels)
        self._levels: dict[int, tuple[int, int, bytes] | None] = {}

    def level(self, index: int) -> tuple[int, int, bytes] | None:
        index = max(0, index)
        if index in self._levels:
            return self._levels[index]
        if index < self.count:
            try:
                self._levels[index] = self.texture.to_rgba(index)
            except Exception:
                self._levels[index] = None
            return self._levels[index]
        base = self.level(self.count - 1)
        if base is None:
            self._levels[index] = None
            return None
        width, height, data = base
        steps = index - self.count + 1
        for _ in range(steps):
            width, height, data = _halve(width, height, data)
            if width < 2 or height < 2:
                break
        self._levels[index] = (width, height, data)
        return self._levels[index]


def _halve(width: int, height: int, data: bytes) -> tuple[int, int, bytes]:
    out_w, out_h = max(1, width // 2), max(1, height // 2)
    out = bytearray(out_w * out_h * 4)
    for y in range(out_h):
        row0 = (y * 2) * width * 4
        row1 = min(y * 2 + 1, height - 1) * width * 4
        for x in range(out_w):
            x0 = (x * 2) * 4
            x1 = min(x * 2 + 1, width - 1) * 4
            for channel in range(4):
                total = (
                    data[row0 + x0 + channel]
                    + data[row0 + x1 + channel]
                    + data[row1 + x0 + channel]
                    + data[row1 + x1 + channel]
                )
                out[(y * out_w + x) * 4 + channel] = total // 4
    return out_w, out_h, bytes(out)


def _decode(
    wire: list,
    textures: dict[str, BtxTexture],
) -> list[tuple[object, "_Surface | None"]]:
    """Resolve each (mesh, material) pair to its textured surface."""
    cache: dict[str, _Surface | None] = {}
    result = []
    for mesh, material in wire:
        key = ""
        if material is not None:
            key = getattr(material, "texture", "") or getattr(material, "name", "")
        if key and key not in cache:
            texture = textures.get(key)
            if texture is None and "." in key:
                texture = textures.get(key.rsplit(".", 1)[0])
            cache[key] = _Surface(texture) if texture is not None else None
        result.append((mesh, cache.get(key) if key else None))
    return result


def _mip_level(surface: "_Surface", ua, ub, uc, screen_area: float) -> int:
    """Pick a mip level from the triangle's texel-per-pixel footprint."""
    width, height = surface.texture.header.width, surface.texture.header.height
    du = max(abs(ua[0] - ub[0]), abs(ub[0] - uc[0]), abs(uc[0] - ua[0])) * width
    dv = max(abs(ua[1] - ub[1]), abs(ub[1] - uc[1]), abs(uc[1] - ua[1])) * height
    footprint = max(du, dv)
    pixels = max(abs(screen_area), 1e-6) ** 0.5
    ratio = max(footprint / pixels, 1e-9)
    limit = max(1, int(math.log2(max(width, height))))
    return max(0, min(int(math.log2(ratio)), limit))


def _uv_scale(mesh, uvs, width: int, height: int, samples: int = 256) -> float | None:
    """Median texels per world unit for a mesh.

    Stage meshes carry a few vertices whose UV is garbage (``|u|`` in the tens
    of thousands) even though their neighbours are continuous. Deciding the mip
    from a single triangle's UV span makes those triangles collapse to the 1x1
    level, painting flat slabs over the stage, so the mesh-wide median is used
    instead.
    """
    if not uvs or not mesh.indices:
        return None
    ratios: list[float] = []
    step = max(1, mesh.triangle_count // samples)
    for triangle in range(0, mesh.triangle_count, step):
        a, b, c = mesh.indices[triangle * 3 : triangle * 3 + 3]
        if max(a, b, c) >= len(uvs):
            continue
        for i, j in ((a, b), (b, c), (c, a)):
            du = (uvs[i][0] - uvs[j][0]) * width
            dv = (uvs[i][1] - uvs[j][1]) * height
            if not (math.isfinite(du) and math.isfinite(dv)):
                continue
            p, q = mesh.positions[i], mesh.positions[j]
            world = math.dist(p, q)
            if world < 1e-6:
                continue
            ratio = math.hypot(du, dv) / world
            if ratio > 0.0:
                ratios.append(ratio)
    if not ratios:
        return None
    ratios.sort()
    return ratios[len(ratios) // 2]


def _solve4(matrix: list[list[float]], vector: list[float]) -> list[float] | None:
    """Solve a 4x4 linear system with partial pivoting."""
    rows = [row[:] + [value] for row, value in zip(matrix, vector)]
    for column in range(4):
        pivot = max(range(column, 4), key=lambda r: abs(rows[r][column]))
        if abs(rows[pivot][column]) < 1e-12:
            return None
        rows[column], rows[pivot] = rows[pivot], rows[column]
        scale = rows[column][column]
        rows[column] = [value / scale for value in rows[column]]
        for other in range(4):
            if other == column:
                continue
            factor = rows[other][column]
            if factor:
                rows[other] = [
                    value - factor * base
                    for value, base in zip(rows[other], rows[column])
                ]
    return [rows[i][4] for i in range(4)]


def _fit_plane(points: list[tuple[float, float, float]], values: list[float]):
    """Least-squares fit ``a*x + b*y + c*z + d`` and return (coefficients, residual).

    A tiny ridge keeps the normal equations solvable when the mesh is flat
    along one axis (walls, floors), which would otherwise leave that coefficient
    undetermined.
    """
    normal = [[0.0] * 4 for _ in range(4)]
    rhs = [0.0] * 4
    for point, value in zip(points, values):
        row = (point[0], point[1], point[2], 1.0)
        for i in range(4):
            rhs[i] += row[i] * value
            for j in range(4):
                normal[i][j] += row[i] * row[j]
    ridge = 1e-6 * max(1.0, max(normal[i][i] for i in range(4)))
    for i in range(4):
        normal[i][i] += ridge
    coefficients = _solve4(normal, rhs)
    if coefficients is None:
        return None, []
    residuals = [
        abs(coefficients[0] * p[0] + coefficients[1] * p[1] + coefficients[2] * p[2]
            + coefficients[3] - value)
        for p, value in zip(points, values)
    ]
    return coefficients, residuals


def _repair_uvs(mesh) -> list[tuple[float, float]] | None:
    """Replace stage UV outliers with a robust planar fit.

    Some stage vertices carry UVs whose magnitude is hundreds of times larger
    than their neighbours' (the authored mapping is a world-space projection, so
    the majority of vertices lie on a plane in UV space). Vertices whose UV
    magnitude is far outside the mesh median are dropped, the plane is fitted to
    the rest, and only the dropped vertices are rewritten from the fit; meshes
    whose UVs are already coherent are returned untouched (``None``).
    """
    count = len(mesh.uvs)
    if count < 8 or count != len(mesh.positions):
        return None
    if not all(math.isfinite(value) for uv in mesh.uvs for value in uv):
        return None
    if max(max(abs(uv[0]), abs(uv[1])) for uv in mesh.uvs) < 32.0:
        # Character UVs are normalised; only stage meshes need the check.
        return None
    points = [(p[0], p[1], p[2]) for p in mesh.positions]
    columns = ([uv[0] for uv in mesh.uvs], [uv[1] for uv in mesh.uvs])
    sane = []
    for axis in (0, 1):
        ordered = sorted(abs(value) for value in columns[axis])
        limit = max(16.0, ordered[len(ordered) // 2] * 32.0)
        sane.append({i for i, value in enumerate(columns[axis]) if abs(value) <= limit})
    kept = sorted(sane[0] & sane[1])
    if len(kept) < 8 or len(kept) == count:
        return None
    channels = []
    for axis in (0, 1):
        coefficients, _residuals = _fit_plane(
            [points[i] for i in kept], [columns[axis][i] for i in kept]
        )
        if coefficients is None:
            return None
        channels.append(coefficients)
    residuals = [
        max(
            abs(channels[0][0] * p[0] + channels[0][1] * p[1] + channels[0][2] * p[2]
                + channels[0][3] - uv[0]),
            abs(channels[1][0] * p[0] + channels[1][1] * p[1] + channels[1][2] * p[2]
                + channels[1][3] - uv[1]),
        )
        for p, uv in zip(points, mesh.uvs)
    ]
    ordered = sorted(residuals[i] for i in kept)
    limit = max(0.25, ordered[len(ordered) // 2] * 8.0)
    if not any(residuals[i] > limit for i in range(count)):
        return None
    repaired = list(mesh.uvs)
    for i, point in enumerate(points):
        if residuals[i] <= limit:
            continue
        repaired[i] = (
            channels[0][0] * point[0] + channels[0][1] * point[1]
            + channels[0][2] * point[2] + channels[0][3],
            channels[1][0] * point[0] + channels[1][1] * point[1]
            + channels[1][2] * point[2] + channels[1][3],
        )
    return repaired


def _mip_from_world(scale: float, pa, pb, pc, screen_area: float, limit: int) -> int:
    edge = max(math.dist(pa, pb), math.dist(pb, pc), math.dist(pc, pa))
    footprint = max(scale * edge, 1e-9)
    pixels = max(abs(screen_area), 1e-6) ** 0.5
    ratio = max(footprint / pixels, 1e-9)
    return max(0, min(int(math.log2(ratio)), limit))


def _additive(material) -> bool:
    """True for the glow layers that the game draws additively.

    The blend mode is not stored in the model: every ``MATE`` chunk is 72 bytes
    with no flags and every ``DRAW`` entry has ``flags = 0``. The stage's glow
    quads can be recognised by name instead — their textures are bright masks
    (``s01_floorglow_mask`` averages 198,198,198) that are meant to brighten the
    surface below rather than cover it. Drawing them as opaque geometry paints
    flat grey sheets over the dance floor.
    """
    if material is None:
        return False
    name = (getattr(material, "name", "") or "").lower()
    if name.startswith("glow"):
        return True
    return any(token in name for token in ADDITIVE_NAMES)


def render_buffer(
    wire: list,
    textures: dict[str, BtxTexture],
    width: int = 512,
    height: int = 768,
    camera: Camera | None = None,
    background: tuple[int, int, int, int] = BACKGROUND,
    ortho_margin: int = 16,
    base: tuple[bytes, list[float]] | None = None,
) -> tuple[bytes, list[float]]:
    """Rasterise (mesh, material) pairs into an RGBA buffer plus a depth buffer.

    Passing ``base`` reuses a previously rendered layer (the static stage), which
    keeps per-frame live renders cheap: only the characters are rasterised.
    """
    items = _decode(wire, textures)
    flags = [_additive(material) for _mesh, material in wire]
    # Additive layers are rasterised last and never write depth, so they
    # brighten whatever lies behind them without hiding it.
    order = sorted(range(len(items)), key=lambda index: flags[index])
    items = [items[index] for index in order]
    flags = [flags[index] for index in order]
    meshes = [mesh for mesh, _canvas in items]
    if not meshes and base is None:
        raise ValueError("no meshes to render")

    if base is None:
        pixels = bytearray(width * height * 4)
        for i in range(width * height):
            pixels[i * 4 : i * 4 + 4] = bytes(background)
        depth = [float("inf")] * (width * height)
    else:
        pixels = bytearray(base[0])
        depth = list(base[1])

    light = _normalize((-0.4, -0.85, 0.35))

    if camera is None:
        if meshes:
            min_x, max_x, min_z, max_z = _screen_bounds(meshes)
            span_x = max(max_x - min_x, 1e-6)
            span_z = max(max_z - min_z, 1e-6)
            scale = min(
                (width - 2 * ortho_margin) / span_x,
                (height - 2 * ortho_margin) / span_z,
            )
        else:
            min_x = min_z = 0.0
            scale = 1.0

    for (mesh, canvas), additive in zip(items, flags):
        if not mesh.indices:
            continue
        if camera is None:
            screen = [
                (
                    (p[0] - min_x) * scale + ortho_margin,
                    height - 1 - ((p[2] - min_z) * scale + ortho_margin),
                    p[1],
                    1.0,
                )
                for p in mesh.positions
            ]
        else:
            view_projection = camera.matrices(width / max(height, 1))
            screen = []
            for p in mesh.positions:
                x = (
                    view_projection[0][0] * p[0]
                    + view_projection[0][1] * p[1]
                    + view_projection[0][2] * p[2]
                    + view_projection[0][3]
                )
                y = (
                    view_projection[1][0] * p[0]
                    + view_projection[1][1] * p[1]
                    + view_projection[1][2] * p[2]
                    + view_projection[1][3]
                )
                z = (
                    view_projection[2][0] * p[0]
                    + view_projection[2][1] * p[1]
                    + view_projection[2][2] * p[2]
                    + view_projection[2][3]
                )
                w = (
                    view_projection[3][0] * p[0]
                    + view_projection[3][1] * p[1]
                    + view_projection[3][2] * p[2]
                    + view_projection[3][3]
                )
                if w <= 1e-6:
                    screen.append(None)
                else:
                    screen.append(
                        (
                            (x / w * 0.5 + 0.5) * width,
                            (0.5 - y / w * 0.5) * height,
                            z / w,
                            w,
                        )
                    )
        uvs = _repair_uvs(mesh) or mesh.uvs
        has_uv = bool(uvs)
        has_normal = bool(mesh.normals)
        scale = None
        limit = 0
        if canvas is not None:
            width_px, height_px = canvas.texture.header.width, canvas.texture.header.height
            limit = max(1, int(math.log2(max(width_px, height_px))))
            if has_uv:
                scale = _uv_scale(mesh, uvs, width_px, height_px)
        for triangle in range(mesh.triangle_count):
            a, b, c = mesh.indices[triangle * 3 : triangle * 3 + 3]
            if a >= len(screen) or b >= len(screen) or c >= len(screen):
                continue
            sa, sb, sc = screen[a], screen[b], screen[c]
            if sa is None or sb is None or sc is None:
                continue
            ax, ay, az, aw = sa
            bx, by, bz, bw = sb
            cx, cy, cz, cw = sc
            area = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax)
            if abs(area) < 1e-9:
                continue
            min_px = max(0, int(min(ax, bx, cx)))
            max_px = min(width - 1, int(max(ax, bx, cx)) + 1)
            min_py = max(0, int(min(ay, by, cy)))
            max_py = min(height - 1, int(max(ay, by, cy)) + 1)
            if min_px > max_px or min_py > max_py:
                continue
            if has_uv:
                ua, ub, uc = uvs[a], uvs[b], uvs[c]
                uv_ok = all(math.isfinite(c) for uv in (ua, ub, uc) for c in uv)
            else:
                ua = ub = uc = (0.0, 0.0)
                uv_ok = False
            if has_normal:
                na, nb, nc = mesh.normals[a], mesh.normals[b], mesh.normals[c]
            else:
                na = nb = nc = (0.0, 0.0, 1.0)
            mip = 0
            if canvas is not None and uv_ok:
                if scale is not None:
                    mip = _mip_from_world(
                        scale,
                        mesh.positions[a],
                        mesh.positions[b],
                        mesh.positions[c],
                        area,
                        limit,
                    )
                else:
                    mip = _mip_level(canvas, ua, ub, uc, area)
            level = canvas.level(mip) if canvas is not None else None
            inv_area = 1.0 / area
            ia, ib, ic = 1.0 / aw, 1.0 / bw, 1.0 / cw
            for py in range(min_py, max_py + 1):
                fy = py + 0.5
                for px in range(min_px, max_px + 1):
                    fx = px + 0.5
                    w0 = ((bx - ax) * (fy - ay) - (by - ay) * (fx - ax)) * inv_area
                    w1 = ((cx - bx) * (fy - by) - (cy - by) * (fx - bx)) * inv_area
                    w2 = 1.0 - w0 - w1
                    if w0 < 0.0 or w1 < 0.0 or w2 < 0.0:
                        continue
                    inv_w = w0 * ia + w1 * ib + w2 * ic
                    if inv_w <= 0.0:
                        continue
                    index = py * width + px
                    z = (w0 * az * ia + w1 * bz * ib + w2 * cz * ic) / inv_w
                    if z >= depth[index]:
                        continue
                    if level is None:
                        color = (180, 180, 180, 255)
                    else:
                        tw, th, data = level
                        u = (w0 * ua[0] * ia + w1 * ub[0] * ib + w2 * uc[0] * ic) / inv_w
                        v = (w0 * ua[1] * ia + w1 * ub[1] * ib + w2 * uc[1] * ic) / inv_w
                        if not (math.isfinite(u) and math.isfinite(v)):
                            if additive:
                                continue
                            color = (180, 180, 180, 255)
                            depth[index] = z
                            pixels[index * 4 : index * 4 + 4] = bytes(color)
                            continue
                        tx = int(u * tw) % tw
                        ty = int((1.0 - v) * th) % th
                        offset = (ty * tw + tx) * 4
                        color = tuple(data[offset : offset + 4])
                    nx = w0 * na[0] + w1 * nb[0] + w2 * nc[0]
                    ny = w0 * na[1] + w1 * nb[1] + w2 * nc[1]
                    nz = w0 * na[2] + w1 * nb[2] + w2 * nc[2]
                    normal_length = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
                    lambert = abs((nx * light[0] + ny * light[1] + nz * light[2]) / normal_length)
                    if not math.isfinite(lambert):
                        lambert = 1.0
                    shade = 0.72 + 0.28 * min(1.0, lambert)
                    offset = index * 4
                    if additive:
                        gain = shade * ADDITIVE_GAIN
                        pixels[offset] = min(255, pixels[offset] + int(color[0] * gain))
                        pixels[offset + 1] = min(
                            255, pixels[offset + 1] + int(color[1] * gain)
                        )
                        pixels[offset + 2] = min(
                            255, pixels[offset + 2] + int(color[2] * gain)
                        )
                        continue
                    depth[index] = z
                    pixels[offset : offset + 4] = bytes(
                        (
                            min(255, int(color[0] * shade)),
                            min(255, int(color[1] * shade)),
                            min(255, int(color[2] * shade)),
                            255,
                        )
                    )
    return bytes(pixels), depth


def encode_sheet(
    tiles: list[bytes],
    tile_width: int,
    tile_height: int,
    columns: int,
    background: tuple[int, int, int, int] = BACKGROUND,
) -> bytes:
    """Tile several RGBA frames into one PNG (a contact sheet)."""
    if not tiles:
        raise ValueError("no tiles to compose")
    columns = max(1, min(columns, len(tiles)))
    rows = (len(tiles) + columns - 1) // columns
    width = tile_width * columns
    height = tile_height * rows
    pixels = bytearray(width * height * 4)
    for index in range(width * height):
        pixels[index * 4 : index * 4 + 4] = bytes(background)
    stride = tile_width * 4
    for index, tile in enumerate(tiles):
        column = index % columns
        row = index // columns
        for y in range(tile_height):
            source = y * stride
            target = ((row * tile_height + y) * width + column * tile_width) * 4
            pixels[target : target + stride] = tile[source : source + stride]
    return encode_png(width, height, bytes(pixels))


def render_meshes(
    wire: list,
    textures: dict[str, BtxTexture],
    width: int = 512,
    height: int = 768,
    camera: Camera | None = None,
    background: tuple[int, int, int, int] = BACKGROUND,
    ortho_margin: int = 16,
) -> bytes:
    """Rasterise (mesh, material) pairs and return a PNG."""
    pixels, _depth = render_buffer(
        wire,
        textures,
        width,
        height,
        camera=camera,
        background=background,
        ortho_margin=ortho_margin,
    )
    return encode_png(width, height, pixels)


def render_textured(
    meshes: list,
    bindings: dict,
    textures: dict[str, BtxTexture],
    width: int = 512,
    height: int = 768,
) -> bytes:
    """Front orthographic preview, fitted to the geometry."""
    wire = [(mesh, bindings.get(index)) for index, mesh in enumerate(meshes)]
    return render_meshes(wire, textures, width, height, camera=None)


def render_camera(
    meshes: list,
    bindings: dict,
    textures: dict[str, BtxTexture],
    camera: Camera,
    width: int = 512,
    height: int = 288,
) -> bytes:
    """Perspective preview from an explicit camera."""
    wire = [(mesh, bindings.get(index)) for index, mesh in enumerate(meshes)]
    return render_meshes(wire, textures, width, height, camera=camera)
